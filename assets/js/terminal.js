// Interactive prompt. The pages work without this script; it only adds the
// typed-command layer on top of the static HTML.
(() => {
  'use strict';

  const body = document.body;
  const form = document.getElementById('prompt');
  const output = document.getElementById('output');
  const staticEl = document.getElementById('static');
  if (!form || !output) return;

  const input = form.querySelector('input');
  const cwd = body.dataset.cwd ? body.dataset.cwd.split('/') : [];
  const user = body.dataset.user || 'guest';
  const host = body.dataset.host || 'localhost';
  const homeUrl = body.dataset.home || '/';
  const HISTORY_KEY = 'terminal-history';

  document.documentElement.classList.add('js');
  form.hidden = false;

  // 404 page: show the path that was requested.
  for (const id of ['missing-path', 'missing-path-echo']) {
    const node = document.getElementById(id);
    if (!node) continue;
    let requested = location.pathname;
    try { requested = decodeURIComponent(requested); } catch { /* malformed escape: show it as typed */ }
    node.textContent = requested.replace(/^\/|\/$/g, '') || '/';
  }

  // ---- Virtual filesystem, generated by Hugo as /index.json ----

  let fs = [];
  const ready = fetch(body.dataset.index)
    .then((r) => (r.ok ? r.json() : []))
    .then((items) => { fs = Array.isArray(items) ? items : []; })
    .catch(() => { fs = []; });

  const parentOf = (path) => (path.includes('/') ? path.slice(0, path.lastIndexOf('/')) : '');
  const baseOf = (path) => path.slice(path.lastIndexOf('/') + 1);

  // Turns a typed path into path segments relative to ~.
  const resolve = (arg = '') => {
    let parts = [...cwd];
    let rest = arg;
    if (arg === '~' || arg.startsWith('~/') || arg.startsWith('/')) {
      parts = [];
      rest = arg.replace(/^~?\/?/, '');
    }
    for (const seg of rest.split('/')) {
      if (!seg || seg === '.') continue;
      if (seg === '..') parts.pop();
      else parts.push(seg);
    }
    return parts;
  };

  const lookup = (parts) => {
    if (!parts.length) return { path: '', url: homeUrl, title: 'home', dir: true };
    const path = parts.join('/');
    return fs.find((i) => i.path === path)
      || fs.find((i) => !i.dir && i.path === `${path}.md`)
      || null;
  };

  const childrenOf = (dirPath) => fs
    .filter((i) => parentOf(i.path) === dirPath)
    // Menu order first (weight comes from the top menu), then directories, then pages with a
    // `weight` in their front matter ("order"), then newest first, then by name.
    .sort((a, b) => ((a.weight ?? 1000) - (b.weight ?? 1000)) || (b.dir - a.dir)
      || ((a.order || Infinity) - (b.order || Infinity) || 0)
      || (b.date || '').localeCompare(a.date || '') || a.path.localeCompare(b.path));

  // ---- Output helpers (text is always inserted as text, never as HTML) ----

  const el = (tag, className, text) => {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  };

  const print = (content, className = '') => {
    const line = el('div', `line ${className}`.trim());
    line.append(content);
    output.append(line);
    return line;
  };

  const promptPath = () => `~${cwd.length ? `/${cwd.join('/')}` : ''}`;

  const echo = (text) => {
    const line = el('p', 'prompt-line');
    const ps1 = el('span', 'ps1');
    ps1.append(el('span', 'user', `${user}@${host}`), ':', el('span', 'path', promptPath()), '$');
    line.append(ps1, ' ', el('span', 'cmd', text));
    output.append(line);
  };

  const entryLink = (item) => {
    const link = el('a', item.dir ? 'dir' : 'file', baseOf(item.path) + (item.dir ? '/' : ''));
    link.href = item.url;
    return link;
  };

  const go = (url) => { location.assign(url); };

  // ---- Commands ----

  const commands = {
    help: {
      desc: 'show this list',
      run() {
        const table = el('div', 'help-table');
        for (const [name, cmd] of Object.entries(commands)) {
          if (cmd.hidden) continue;
          table.append(el('span', 'name', cmd.usage || name), el('span', 'desc', cmd.desc));
        }
        print(table);
        print('Tab completes, Up/Down browse history, Ctrl+L clears.', 'hint');
        const more = el('span', '', 'Not everything is listed. See ');
        const tryMe = lookup(['try-me']);
        const link = el('a', '', 'cat ~/try-me.md');
        if (tryMe) link.href = tryMe.url;
        more.append(tryMe ? link : 'what a real server would accept', '.');
        print(more, 'hint');
      },
    },

    ls: {
      usage: 'ls [-l] [path]',
      desc: 'list pages and sections',
      run(args) {
        const long = args.some((a) => a.startsWith('-') && a.includes('l'));
        const target = args.find((a) => !a.startsWith('-')) || '';
        const item = lookup(resolve(target));
        if (!item) {
          print(`ls: cannot access '${target}': No such file or directory`, 'error');
          return;
        }
        const items = item.dir ? childrenOf(item.path) : [item];
        if (!long) {
          const list = el('ul', 'ls-short');
          for (const i of items) {
            const li = el('li');
            li.append(entryLink(i));
            list.append(li);
          }
          print(list);
          return;
        }
        const list = el('ul', 'ls-long');
        for (const i of items) {
          const li = el('li');
          li.append(
            el('span', 'perms', i.dir ? 'drwxr-xr-x' : '-rw-r--r--'),
            el('span', 'date', i.date || '----------'),
            entryLink(i),
            el('span', 'desc', `# ${i.title}`),
          );
          list.append(li);
        }
        print(`total ${items.length}`, 'total');
        print(list);
      },
    },

    cd: {
      usage: 'cd [dir]',
      desc: 'open a section (cd .. goes up, cd goes home)',
      run(args) {
        const target = args[0] || '~';
        if (target === '-') {
          history.back();
          return;
        }
        const item = lookup(resolve(target));
        if (!item) print(`bash: cd: ${target}: No such file or directory`, 'error');
        else if (!item.dir) print(`bash: cd: ${target}: Not a directory`, 'error');
        else go(item.url);
      },
    },

    cat: {
      usage: 'cat <file>',
      desc: 'open a page',
      run(args) {
        const target = args[0];
        if (!target) {
          print('cat: missing file operand', 'error');
          return;
        }
        const item = lookup(resolve(target));
        if (!item && /(^|\/)\.[^./]/.test(target)) print(`cat: ${target}: Permission denied. Nice try.`, 'error');
        else if (!item) print(`cat: ${target}: No such file or directory`, 'error');
        else if (item.dir) print(`cat: ${target}: Is a directory`, 'error');
        else go(item.url);
      },
    },

    pwd: {
      desc: 'print the current directory',
      run() { print(`/home/${user}${cwd.length ? `/${cwd.join('/')}` : ''}`); },
    },

    whoami: {
      desc: 'who you are, and whose site this is',
      run() {
        print(user);
        if (body.dataset.bio) print(`You are visiting the site of ${body.dataset.bio}`);
        const about = lookup(['about']);
        if (about) {
          const line = el('span', 'desc', '# more: ');
          const link = el('a', '', 'cat ~/about.md');
          link.href = about.url;
          line.append(link);
          print(line);
        }
      },
    },

    history: {
      desc: 'show typed commands',
      run() {
        typed.forEach((line, i) => print(`${String(i + 1).padStart(4)}  ${line}`));
      },
    },

    clear: {
      desc: 'clear the screen',
      run() { clearScreen(); },
    },

    echo: { hidden: true, run(args) { print(args.join(' ')); } },
    date: { hidden: true, run() { print(new Date().toString()); } },
  };

  // ---- Easter eggs (hidden from help and from Tab completion) ----

  const FORTUNES = [
    'It was DNS. It is always DNS.',
    'There is no cloud. It is just someone else\'s computer.',
    'It works on my machine. Then we ship my machine.',
    'Everybody has a testing environment. Some are lucky enough to have a separate production one.',
    'A deploy on Friday is a gift to your weekend self. Not a nice one.',
    'YAML: because JSON had too few ways to be wrong.',
    'The best time to set up backups was before the outage. The second best time is now.',
  ];
  const daysSince = (date) => Math.max(0, Math.floor((Date.now() - Date.parse(date)) / 864e5)) || 0;
  const egg = (run) => ({ hidden: true, run });

  Object.assign(commands, {
    sudo: egg((args) => {
      if (args.join(' ') === 'make me a sandwich') print('Okay.');
      else print(`${user} is not in the sudoers file. This incident will be reported.`, 'error');
    }),

    rm: egg(() => print('rm: this is a static site, there is nothing left to break. Nice try.')),

    kubectl: egg((args) => {
      const what = args.slice(0, 2).join(' ');
      const age = `${daysSince('2026-10-17')}d`.padEnd(5);
      if (/^get (nodes?|no)$/.test(what)) {
        print([
          'NAME         STATUS   ROLES           AGE   VERSION',
          `homelab-cp   Ready    control-plane   ${age} v1.36.5+k3s1`,
          `homelab-w1   Ready    <none>          ${age} v1.36.5+k3s1`,
          `homelab-w2   Ready    <none>          ${age} v1.36.5+k3s1`,
        ].join('\n'));
      } else if (/^get (pods?|po)$/.test(what)) {
        print([
          'NAME                        READY   STATUS             RESTARTS   AGE',
          `homepage-6c9d7f5b8-x2kqp    1/1     Running            0          ${age}`,
          `coffee-5f7d8c9b4-zz42p      0/1     CrashLoopBackOff   42         ${age}`,
        ].join('\n'));
      } else {
        print("error: the homelab is not reachable from the internet (by design). Try 'kubectl get nodes' or 'kubectl get pods'.", 'error');
      }
    }),

    vim: egg(() => print('Opening vim... just kidding, you would never get out. (:q works here, though.)')),
    ':q': egg(() => print('You escaped vim. Few do.')),

    exit: egg(() => print('logout\nThere is no exit here, only the close-tab button.')),

    ping: egg((args) => print(`PING ${args[0] || 'afavaccio.cloud'}: 64 bytes, time=0.042 ms\npong`)),

    uptime: egg(() => print(`up ${daysSince(body.dataset.launched)} days, 1 user (you), load average: 0.00, 0.00, 0.00`)),

    fortune: egg(() => print(FORTUNES[Math.floor(Math.random() * FORTUNES.length)])),

    cowsay: egg((args) => {
      const text = args.join(' ') || 'moo';
      print([
        ` ${'_'.repeat(text.length + 2)}`,
        `< ${text} >`,
        ` ${'-'.repeat(text.length + 2)}`,
        String.raw`        \   ^__^`,
        String.raw`         \  (oo)\_______`,
        String.raw`            (__)\       )\/\ `,
        '                ||----w |',
        '                ||     ||',
      ].join('\n'));
    }),

    neofetch: egg(() => print([
      `${user}@${host}`,
      '-'.repeat(`${user}@${host}`.length),
      'OS:      Static HTML, no moving parts',
      'Host:    GitHub Pages',
      'Kernel:  Hugo',
      'Shell:   bash (a very small imitation)',
      'Theme:   Catppuccin Mocha',
      `Uptime:  ${daysSince(body.dataset.launched)} days`,
      `Pages:   ${fs.filter((i) => !i.dir).length}`,
    ].join('\n'))),

    make: egg((args) => {
      if (args.length) print(`make: *** No rule to make target '${args[0]}'.  Stop.`, 'error');
      else print('make: *** No targets specified and no makefile found.  Stop.', 'error');
    }),

    git: egg((args) => {
      if (args[0] === 'push' && args.some((a) => a === '--force' || a === '-f')) {
        print('remote: rejected. Force-pushing to main? Not on my watch.', 'error');
      } else if (args[0] === 'blame') {
        print('It was DNS. It is always DNS.');
      } else {
        print('Nothing to do: this site deploys itself on every push.');
      }
    }),

    man: egg(() => print("What manual page do you want? (This shell only has 'help'.)")),

    coffee: egg(() => print("error 418: I'm a teapot.", 'error')),

    hello: egg(() => print("Hello! Type 'help' to look around.")),
  });
  for (const [alias, name] of [['vi', 'vim'], ['nano', 'vim'], ['emacs', 'vim'], [':q!', ':q'], [':wq', ':q'], ['logout', 'exit'], ['hi', 'hello']]) {
    commands[alias] = commands[name];
  }
  commands.open = { hidden: true, run: (args) => {
    const item = args[0] ? lookup(resolve(args[0])) : null;
    if (item) go(item.url);
    else print(`open: ${args[0] || ''}: No such file or directory`, 'error');
  } };

  const clearScreen = () => {
    if (staticEl) staticEl.hidden = true;
    output.replaceChildren();
  };

  // ---- History (kept for the tab session so it survives page changes) ----

  let typed = [];
  try {
    const saved = JSON.parse(sessionStorage.getItem(HISTORY_KEY));
    if (Array.isArray(saved)) typed = saved.filter((s) => typeof s === 'string');
  } catch { /* storage unavailable: history lives in memory only */ }
  let cursor = typed.length;
  let draft = '';

  const remember = (line) => {
    if (typed[typed.length - 1] !== line) typed.push(line);
    typed = typed.slice(-100);
    try { sessionStorage.setItem(HISTORY_KEY, JSON.stringify(typed)); } catch { /* ignore */ }
  };

  // ---- Tab completion ----

  const commonPrefix = (words) => {
    let prefix = words[0] || '';
    for (const w of words) {
      while (!w.startsWith(prefix)) prefix = prefix.slice(0, -1);
    }
    return prefix;
  };

  const complete = () => {
    const value = input.value;
    const tokens = value.split(/\s+/);
    const last = tokens[tokens.length - 1];
    let candidates;
    let head = '';

    if (tokens.length === 1) {
      candidates = Object.keys(commands)
        .filter((n) => !commands[n].hidden && n.startsWith(last))
        .map((n) => `${n} `);
    } else {
      const slash = last.lastIndexOf('/');
      head = slash >= 0 ? last.slice(0, slash + 1) : '';
      const partial = last.slice(slash + 1);
      const dir = lookup(resolve(head));
      if (!dir || !dir.dir) return;
      candidates = childrenOf(dir.path)
        .map((i) => baseOf(i.path) + (i.dir ? '/' : ''))
        .filter((n) => n.startsWith(partial));
    }

    if (!candidates.length) return;
    const prefix = commonPrefix(candidates);
    tokens[tokens.length - 1] = head + prefix;
    input.value = tokens.join(' ');
    if (candidates.length > 1) {
      echo(value);
      print(candidates.join('  '));
      form.scrollIntoView({ block: 'nearest' });
    }
  };

  // ---- Events ----

  form.addEventListener('submit', async (event) => {
    event.preventDefault();
    const raw = input.value;
    const line = raw.trim();
    input.value = '';
    echo(raw);
    if (line) {
      remember(line);
      await ready;
      const [name, ...args] = line.split(/\s+/);
      const command = Object.hasOwn(commands, name) ? commands[name] : null;
      if (command) command.run(args);
      else print(`bash: ${name}: command not found`, 'error');
    }
    cursor = typed.length;
    draft = '';
    form.scrollIntoView({ block: 'nearest' });
  });

  input.addEventListener('keydown', async (event) => {
    if (event.key === 'ArrowUp') {
      event.preventDefault();
      if (cursor === typed.length) draft = input.value;
      if (cursor > 0) input.value = typed[--cursor];
    } else if (event.key === 'ArrowDown') {
      event.preventDefault();
      if (cursor < typed.length) {
        cursor += 1;
        input.value = cursor === typed.length ? draft : typed[cursor];
      }
    } else if (event.key === 'Tab' && !event.shiftKey && input.value.trim()) {
      // An empty prompt lets Tab move focus as usual.
      event.preventDefault();
      await ready;
      complete();
    } else if (event.ctrlKey && event.key.toLowerCase() === 'l') {
      event.preventDefault();
      clearScreen();
    } else if (event.ctrlKey && event.key.toLowerCase() === 'c' && input.selectionStart === input.selectionEnd) {
      event.preventDefault();
      echo(`${input.value}^C`);
      input.value = '';
      cursor = typed.length;
    }
  });

  // Clicking empty terminal space focuses the prompt, without breaking text selection or links.
  document.getElementById('screen').addEventListener('click', (event) => {
    // Commands written in a page with the `cmd` shortcode run when clicked.
    const runnable = event.target.closest('.run');
    if (runnable) {
      input.value = runnable.dataset.cmd;
      form.requestSubmit();
      return;
    }
    if (event.target.closest('a, input, button')) return;
    if (String(window.getSelection())) return;
    input.focus({ preventScroll: true });
  });

  // Focus on load only with a real keyboard, so phones do not pop up the on-screen one.
  if (window.matchMedia('(pointer: fine)').matches) input.focus({ preventScroll: true });
})();
